/**
 * Фотографии сайта. Пока реальных снимков нет, у каждого места есть арт-бриф —
 * по нему видно, какой кадр нужен, и его можно отдать фотографу как список съёмки.
 *
 * Как заменить заглушку:
 *   1. положите файл в src/assets/photos/ (JPG/PNG, от 2400 px по длинной стороне);
 *   2. импортируйте его здесь: import hall from '../assets/photos/hall.jpg';
 *   3. укажите src: hall у нужного слота. Размеры, AVIF/WebP и lazy loading — автоматически.
 *
 * Фотостиль: тёплый естественный или вечерний свет, глубокие тени без пересвета,
 * тёплый баланс белого, фактура посуды и стола. Блюда — сверху или с уровня стола,
 * без «стоковых» улыбок в камеру. Люди — в движении, в работе, без позирования.
 */
import type { ImageMetadata } from 'astro';

export type Tone = 'paper' | 'clay' | 'olive' | 'tomato' | 'ink';

export interface PhotoSlot {
  /** Подключённый файл; пока нет — показывается заглушка с брифом */
  src?: ImageMetadata;
  /** Альтернативный текст для реальной фотографии */
  alt: string;
  /** Что должно быть в кадре — видно на заглушке */
  brief: string;
  /** Пропорции кадра: «4/5», «3/2», «1/1» … */
  ratio: string;
  tone: Tone;
}

const slot = (brief: string, ratio: string, tone: Tone, alt = brief): PhotoSlot => ({ brief, ratio, tone, alt });

