/**
 * Меню ресторана «Базилик». Перенесено из печатного меню ресторана: названия, состав, выход и цены.
 * Страница /menu и превью на главной строятся из этого файла — вёрстку при правках трогать не нужно.
 *
 * Как править:
 *   — цена: поле price (в рублях); у напитков с несколькими объёмами — prices;
 *   — выход: portion («550 г», «150/40 г», «40 мл»);
 *   — новинка: isNew: true — рядом с названием появится пометка «новинка»;
 *   — фото блюда: photo (импорт из src/assets/…), пока нет — показывается заглушка.
 *
 * layout:
 *   'gallery' — горизонтальная лента-коллаж с фотографиями (паста, рыба, мясо, десерты);
 *   'list'    — типографский список с ценами.
 */
import type { ImageMetadata } from 'astro';

export interface MenuPrice {
  /** «150 мл», «1000 мл» */
  volume: string;
  price: number;
}

export interface MenuItem {
  name: string;
  /** Состав или короткое описание */
  description?: string;
  /** Выход или объём: «550 г», «150/40 г», «40 мл» */
  portion?: string;
  /** Цена в рублях */
  price?: number;
  /** Несколько объёмов с разной ценой (бокал и бутылка, 200 и 1000 мл) — вместо price */
  prices?: MenuPrice[];
  isNew?: boolean;
  photo?: ImageMetadata;
}

export type MenuGroupId = 'kitchen' | 'drinks' | 'bar' | 'wine';

export interface MenuCategory {
  id: string;
  title: string;
  group: MenuGroupId;
  layout: 'gallery' | 'list';
  /** Пояснение под заголовком раздела */
  note?: string;
  /** Примечания после списка */
  footnotes?: string[];
  items: MenuItem[];
}

