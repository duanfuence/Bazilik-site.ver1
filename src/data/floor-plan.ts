/**
 * Заготовка для интерактивной схемы зала.
 * Данные о столах ресторан пока не передал, поэтому схема на сайте не показывается.
 *
 * Что нужно, чтобы включить выбор стола:
 *   1. план зала (чертёж или фото с размерами) и список столов с вместимостью;
 *   2. правила рассадки (какие столы можно объединять, есть ли зоны у окна/бара);
 *   3. источник занятости — система бронирования ресторана (iiko, r_keeper, Restoplace и т. п.) с API.
 *      Без реальной занятости показывать «свободные столы» нельзя: это ввело бы гостя в заблуждение.
 */
export interface Table {
  id: string;
  /** Подпись на схеме: «7», «Бар 2» */
  label: string;
  seats: { min: number; max: number };
  zone: string;
  /** Положение и размер на схеме в условных единицах (0–100) */
  x: number;
  y: number;
  w: number;
  h: number;
  shape: 'round' | 'rect';
}

export interface Zone {
  id: string;
  title: string;
}

export const zones: Zone[] = [];
export const tables: Table[] = [];
